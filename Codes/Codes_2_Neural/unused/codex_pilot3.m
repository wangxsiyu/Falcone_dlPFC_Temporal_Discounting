    'Name', 'Relative explained variance in full model', ...
    'Position', [100 100 1150 540]);
relativeVarianceLayout = tiledlayout(1, 2, ...
    'TileSpacing', 'compact', 'Padding', 'compact');
for animalIndex = 1:numel(animalNames)
    nexttile;
    result = pilot3Regression.animals(animalIndex);
    timeAt = result.time_at;
    smoothingBins = max(1, round( ...
        50/median(diff(timeAt))));

    % Smooth the unique sums of squares before converting them to
    % percentages, so that the three stacked contributions remain 100%.
    uniqueSS = smoothdata( ...
        result.population_unique_explained_ss, ...
        2, 'gaussian', smoothingBins);
    uniqueSSTotal = sum(uniqueSS, 1);
    relativeExplainedVariance = 100*uniqueSS./uniqueSSTotal;
    relativeExplainedVariance(:, ...
        ~isfinite(uniqueSSTotal) | uniqueSSTotal <= eps) = nan;

    areaHandles = area(timeAt, ...
        uniqueSS', ...
        'LineStyle', 'none');
    for predictorIndex = 1:numel(predictorNames)
        areaHandles(predictorIndex).FaceColor = ...
            predictorColors(predictorIndex, :);
        areaHandles(predictorIndex).FaceAlpha = 0.85;
    end
    xline(0, '--k', 'LineWidth', 1);
    xlim([-250 1000]);
    % ylim([0 100]);
    set(gca, ...
        'XTick', -250:250:1000, ...
        'YTick', 0:20:100, ...
        'FontSize', 11);
    xlabel('Time from GO cue onset (ms)');
    ylabel('Relative unique explained variance (%)');
    title(animalNames(animalIndex));
    box off;
end
