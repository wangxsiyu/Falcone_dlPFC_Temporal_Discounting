%% Regression of condition-baseline-corrected activity on choice and motor
% Response for trial i belonging to condition k:
%   Delta firing_i(t) = firing_i(t) -
%       mean firing for condition k during -250:0 ms before GO.
%
% Regression at every neuron and time point:
%   Delta firing_i(t) = alpha(t) + beta_C(t) C_i +
%       beta_M(t) M_i + beta_CM(t) C_i*M_i + epsilon_i(t),
% where C and M are effect-coded as -1/+1.

if ~exist('go', 'var')
    data = W.load('../../TempData/data');
    go = data.go;
end

valueAxes = W.load('../../TempData/value_axisGO');
axisWindowIndex = 1;
baselineWindow = [-250 0];
analysisWindows = [0 250; 250 500; 500 750; 750 1000];
animalNames = ["Monkey S", "Monkey T"];
parameterNames = ["Intercept", "Choice", ...
    "Release1", "Choice x Release1"];
componentNames = ["Intercept only", "Choice only", ...
    "Release1 only", "Choice x Release1 only", ...
    "Regression residual"];
animalColors = [0.15 0.45 0.75; 0.75 0.25 0.20];

pilot3Regression = struct;
pilot3Regression.model = [ ...
    "Delta firing(t) ~ 1 + choice + release1 + " ...
    "choice*release1"];
pilot3Regression.response = [ ...
    "Firing rate minus the neuron's condition-specific mean " ...
    "firing rate during -250:0 ms before GO"];
pilot3Regression.parameter_names = parameterNames;
pilot3Regression.component_names = componentNames;
pilot3Regression.reduced_model = ...
    "Delta firing(t) ~ 1 + choice + release1";
pilot3Regression.choice_only_model = ...
    "Delta firing(t) ~ 1 + choice";
pilot3Regression.motor_only_model = ...
    "Delta firing(t) ~ 1 + release1";
pilot3Rows = cell(0, 8);

for animalIndex = 1:numel(animalNames)
    goData = go{animalIndex};
    timeAt = goData.time_at;
    nNeurons = numel(goData.cells);
    nTimes = numel(timeAt);
    nParameters = numel(parameterNames);
    baselineMask = timeAt >= baselineWindow(1) & ...
        timeAt < baselineWindow(2);
    betaTime = nan(nNeurons, nParameters, nTimes);
    uniqueExplainedSS = nan(nNeurons, 3, nTimes);
    fullModelExplainedSS = nan(nNeurons, nTimes);
    totalSS = nan(nNeurons, nTimes);
    reducedBetaTime = nan(nNeurons, 3, nTimes);
    choiceOnlyBetaTime = nan(nNeurons, 2, nTimes);
    motorOnlyBetaTime = nan(nNeurons, 2, nTimes);
    conditionBaselines = nan(nNeurons, 9);
    correctedYPTrajectories = nan(nNeurons, 9, 2, nTimes);
    componentYPTrajectories = nan( ...
        nNeurons, 5, 9, 2, nTimes);
    reducedResidualYPTrajectories = nan( ...
        nNeurons, 9, 2, nTimes);
    choiceOnlyResidualYPTrajectories = nan( ...
        nNeurons, 9, 2, nTimes);
    motorOnlyResidualYPTrajectories = nan( ...
        nNeurons, 9, 2, nTimes);

    for neuronIndex = 1:nNeurons
        spikes = goData.cells{neuronIndex};
        game = goData.games{ ...
            goData.info_cells.gameID(neuronIndex)};
        assert(size(spikes, 1) == height(game), ...
            'Spike trials and behavioral trials must match.');

        deltaSpikes = nan(size(spikes));
        for condition = 1:9
            conditionMask = game.condition == condition;
            baselineValues = spikes(conditionMask, baselineMask);
            conditionBaseline = mean( ...
                baselineValues, 'all', 'omitnan');
            conditionBaselines(neuronIndex, condition) = ...
                conditionBaseline;
            deltaSpikes(conditionMask, :) = ...
                spikes(conditionMask, :) - conditionBaseline;
        end

        choiceCode = 2 * game.choice - 1;
        motorCode = 2 * game.release1 - 1;
        design = [ones(height(game), 1), choiceCode, ...
            motorCode, choiceCode .* motorCode];
        reducedDesign = design(:, 1:3);
        choiceOnlyDesign = design(:, 1:2);
        motorOnlyDesign = design(:, [1 3]);
        validBehavior = all(isfinite(design), 2);

        for timeIndex = 1:nTimes
            validTrials = validBehavior & ...
                isfinite(deltaSpikes(:, timeIndex));
            currentDesign = design(validTrials, :);
            currentReducedDesign = reducedDesign(validTrials, :);
            currentChoiceOnlyDesign = ...
                choiceOnlyDesign(validTrials, :);
            currentMotorOnlyDesign = ...
                motorOnlyDesign(validTrials, :);
            if rank(currentDesign) == nParameters
                currentResponse = deltaSpikes( ...
                    validTrials, timeIndex);
                fullCoefficients = ...
                    currentDesign \ currentResponse;
                betaTime(neuronIndex, :, timeIndex) = ...
                    fullCoefficients;

                fullResidual = currentResponse - ...
                    currentDesign*fullCoefficients;
                fullSSE = sum(fullResidual.^2);
                currentTotalSS = sum((currentResponse - ...
                    mean(currentResponse)).^2);
                totalSS(neuronIndex, timeIndex) = currentTotalSS;
                fullModelExplainedSS(neuronIndex, timeIndex) = ...
                    max(currentTotalSS - fullSSE, 0);

                % Drop one term from the full model at a time. The
                % increase in SSE is that term's unique contribution
                % conditional on the other two behavioral predictors.
                retainedColumns = { ...
                    [1 3 4], ... % omit choice
                    [1 2 4], ... % omit release1
                    [1 2 3]};    % omit choice x release1
                for predictorIndex = 1:numel(retainedColumns)
                    reducedForTerm = currentDesign(:, ...
                        retainedColumns{predictorIndex});
                    if rank(reducedForTerm) == ...
                            size(reducedForTerm, 2)
                        reducedCoefficientsForTerm = ...
                            reducedForTerm \ currentResponse;
                        reducedResidualForTerm = currentResponse - ...
                            reducedForTerm*reducedCoefficientsForTerm;
                        reducedSSEForTerm = ...
                            sum(reducedResidualForTerm.^2);
                        uniqueExplainedSS(neuronIndex, ...
                            predictorIndex, timeIndex) = ...
                            max(reducedSSEForTerm - fullSSE, 0);
                    end
                end
            end
            if rank(currentReducedDesign) == 3
                reducedBetaTime(neuronIndex, :, timeIndex) = ...
                    currentReducedDesign \ deltaSpikes( ...
                    validTrials, timeIndex);
            end
            if rank(currentChoiceOnlyDesign) == 2
                choiceOnlyBetaTime(neuronIndex, :, timeIndex) = ...
                    currentChoiceOnlyDesign \ deltaSpikes( ...
                    validTrials, timeIndex);
            end
            if rank(currentMotorOnlyDesign) == 2
                motorOnlyBetaTime(neuronIndex, :, timeIndex) = ...
                    currentMotorOnlyDesign \ deltaSpikes( ...
                    validTrials, timeIndex);
            end
        end

        betaIntercept = reshape(betaTime(neuronIndex, 1, :), ...
            1, nTimes);
        betaChoice = reshape(betaTime(neuronIndex, 2, :), ...
            1, nTimes);
        betaMotor = reshape(betaTime(neuronIndex, 3, :), ...
            1, nTimes);
        betaInteraction = reshape(betaTime(neuronIndex, 4, :), ...
            1, nTimes);
        interceptComponent = ones(height(game), 1) * ...
            betaIntercept;
        choiceComponent = choiceCode * betaChoice;
        motorComponent = motorCode * betaMotor;
        interactionComponent = (choiceCode .* motorCode) * ...
            betaInteraction;
        residualComponent = deltaSpikes - interceptComponent - ...
            choiceComponent - motorComponent - interactionComponent;
        componentData = {interceptComponent, choiceComponent, ...
            motorComponent, interactionComponent, residualComponent};
        reducedCoefficients = reshape( ...
            reducedBetaTime(neuronIndex, :, :), 3, nTimes);
        reducedResidual = deltaSpikes - ...
            reducedDesign * reducedCoefficients;
        choiceOnlyCoefficients = reshape( ...
            choiceOnlyBetaTime(neuronIndex, :, :), 2, nTimes);
        choiceOnlyResidual = deltaSpikes - ...
            choiceOnlyDesign * choiceOnlyCoefficients;
        motorOnlyCoefficients = reshape( ...
            motorOnlyBetaTime(neuronIndex, :, :), 2, nTimes);
        motorOnlyResidual = deltaSpikes - ...
            motorOnlyDesign * motorOnlyCoefficients;
        correctedDeltaSpikes = deltaSpikes - ...
            choiceComponent - motorComponent;

        isColor = {game.cue1 == "yellow", ...
            game.cue1 == "purple"};
        for condition = 1:9
            for colorIndex = 1:2
                trialMask = game.condition == condition & ...
                    isColor{colorIndex};
                if sum(trialMask) < 10
                    continue;
                end
                trajectory = mean( ...
                    correctedDeltaSpikes(trialMask, :), ...
                    1, 'omitnan');
                trajectory = trajectory - mean( ...
                    trajectory(baselineMask), 'omitnan');
                correctedYPTrajectories(neuronIndex, ...
                    condition, colorIndex, :) = trajectory;
                reducedResidualTrajectory = mean( ...
                    reducedResidual(trialMask, :), ...
                    1, 'omitnan');
                reducedResidualTrajectory = ...
                    reducedResidualTrajectory - mean( ...
                    reducedResidualTrajectory(baselineMask), ...
                    'omitnan');
                reducedResidualYPTrajectories(neuronIndex, ...
                    condition, colorIndex, :) = ...
                    reducedResidualTrajectory;
                choiceOnlyResidualTrajectory = mean( ...
                    choiceOnlyResidual(trialMask, :), ...
                    1, 'omitnan');
                choiceOnlyResidualTrajectory = ...
                    choiceOnlyResidualTrajectory - mean( ...
                    choiceOnlyResidualTrajectory(baselineMask), ...
                    'omitnan');
                choiceOnlyResidualYPTrajectories(neuronIndex, ...
                    condition, colorIndex, :) = ...
                    choiceOnlyResidualTrajectory;
                motorOnlyResidualTrajectory = mean( ...
                    motorOnlyResidual(trialMask, :), ...
                    1, 'omitnan');
                motorOnlyResidualTrajectory = ...
                    motorOnlyResidualTrajectory - mean( ...
                    motorOnlyResidualTrajectory(baselineMask), ...
                    'omitnan');
                motorOnlyResidualYPTrajectories(neuronIndex, ...
                    condition, colorIndex, :) = ...
                    motorOnlyResidualTrajectory;
                for componentIndex = 1:numel(componentNames)
                    componentTrajectory = mean( ...
                        componentData{componentIndex}(trialMask, :), ...
                        1, 'omitnan');
                    componentTrajectory = componentTrajectory - mean( ...
                        componentTrajectory(baselineMask), 'omitnan');
                    componentYPTrajectories(neuronIndex, ...
                        componentIndex, condition, colorIndex, :) = ...
                        componentTrajectory;
                end
            end
        end
    end

    rawValueAxis = valueAxes.animals(animalIndex). ...
        axis_unit(:, axisWindowIndex);
    validNeurons = all(reshape( ...
        isfinite(betaTime), nNeurons, []), 2) & ...
        isfinite(rawValueAxis);
    betaTime(~validNeurons, :, :) = 0;
    valueAxis = rawValueAxis;
    valueAxis(~validNeurons) = 0;
    valueAxis = valueAxis / norm(valueAxis);

    parameterProjection = reshape(valueAxis' * ...
        reshape(betaTime, nNeurons, []), ...
        nParameters, nTimes);

    validCorrectedNeurons = all(reshape( ...
        isfinite(correctedYPTrajectories), ...
        nNeurons, []), 2) & isfinite(rawValueAxis);
    correctedYPTrajectories(~validCorrectedNeurons, :, :, :) = 0;
    correctedValueAxis = rawValueAxis;
    correctedValueAxis(~validCorrectedNeurons) = 0;
    correctedValueAxis = correctedValueAxis / ...
        norm(correctedValueAxis);
    correctedYPProjection = reshape(correctedValueAxis' * ...
        reshape(correctedYPTrajectories, nNeurons, []), ...
        9, 2, nTimes);

    validComponentNeurons = all(reshape( ...
        isfinite(componentYPTrajectories), ...
        nNeurons, []), 2) & isfinite(rawValueAxis);
    componentYPTrajectories(~validComponentNeurons, :, :, :, :) = 0;
    componentValueAxis = rawValueAxis;
    componentValueAxis(~validComponentNeurons) = 0;
    componentValueAxis = componentValueAxis / ...
        norm(componentValueAxis);
    componentYPProjection = reshape(componentValueAxis' * ...
        reshape(componentYPTrajectories, nNeurons, []), ...
        5, 9, 2, nTimes);

    validReducedResidualNeurons = all(reshape( ...
        isfinite(reducedResidualYPTrajectories), ...
        nNeurons, []), 2) & isfinite(rawValueAxis);
    reducedResidualYPTrajectories( ...
        ~validReducedResidualNeurons, :, :, :) = 0;
    reducedResidualValueAxis = rawValueAxis;
    reducedResidualValueAxis(~validReducedResidualNeurons) = 0;
    reducedResidualValueAxis = reducedResidualValueAxis / ...
        norm(reducedResidualValueAxis);
    reducedResidualYPProjection = reshape( ...
        reducedResidualValueAxis' * reshape( ...
        reducedResidualYPTrajectories, nNeurons, []), ...
        9, 2, nTimes);

    validChoiceOnlyResidualNeurons = all(reshape( ...
        isfinite(choiceOnlyResidualYPTrajectories), ...
        nNeurons, []), 2) & isfinite(rawValueAxis);
    choiceOnlyResidualYPTrajectories( ...
        ~validChoiceOnlyResidualNeurons, :, :, :) = 0;
    choiceOnlyResidualValueAxis = rawValueAxis;
    choiceOnlyResidualValueAxis( ...
        ~validChoiceOnlyResidualNeurons) = 0;
    choiceOnlyResidualValueAxis = choiceOnlyResidualValueAxis / ...
        norm(choiceOnlyResidualValueAxis);
    choiceOnlyResidualYPProjection = reshape( ...
        choiceOnlyResidualValueAxis' * reshape( ...
        choiceOnlyResidualYPTrajectories, nNeurons, []), ...
        9, 2, nTimes);

    validMotorOnlyResidualNeurons = all(reshape( ...
        isfinite(motorOnlyResidualYPTrajectories), ...
        nNeurons, []), 2) & isfinite(rawValueAxis);
    motorOnlyResidualYPTrajectories( ...
        ~validMotorOnlyResidualNeurons, :, :, :) = 0;
    motorOnlyResidualValueAxis = rawValueAxis;
    motorOnlyResidualValueAxis( ...
        ~validMotorOnlyResidualNeurons) = 0;
    motorOnlyResidualValueAxis = motorOnlyResidualValueAxis / ...
        norm(motorOnlyResidualValueAxis);
    motorOnlyResidualYPProjection = reshape( ...
        motorOnlyResidualValueAxis' * reshape( ...
        motorOnlyResidualYPTrajectories, nNeurons, []), ...
        9, 2, nTimes);

    populationUniqueSS = reshape(sum( ...
        uniqueExplainedSS, 1, 'omitnan'), 3, nTimes);
    uniqueSSTotal = sum(populationUniqueSS, 1);
    relativeUniqueExplainedVariance = ...
        100*populationUniqueSS./uniqueSSTotal;
    relativeUniqueExplainedVariance(:, ...
        ~isfinite(uniqueSSTotal) | uniqueSSTotal <= eps) = nan;
    populationTotalSS = sum(totalSS, 1, 'omitnan');
    populationFullExplainedSS = sum( ...
        fullModelExplainedSS, 1, 'omitnan');
    populationFullModelR2 = ...
        populationFullExplainedSS./populationTotalSS;
    populationFullModelR2( ...
        ~isfinite(populationTotalSS) | ...
        populationTotalSS <= eps) = nan;

    pilot3Regression.animals(animalIndex).name = ...
        animalNames(animalIndex);
    pilot3Regression.animals(animalIndex).time_at = timeAt;
    pilot3Regression.animals(animalIndex).parameter_projection = ...
        parameterProjection;
    pilot3Regression.animals(animalIndex).condition_baselines = ...
        conditionBaselines;
    pilot3Regression.animals(animalIndex).n_valid_neurons = ...
        sum(validNeurons);
    pilot3Regression.animals(animalIndex). ...
        corrected_YP_projection = correctedYPProjection;
    pilot3Regression.animals(animalIndex). ...
        n_valid_corrected_neurons = sum(validCorrectedNeurons);
    pilot3Regression.animals(animalIndex). ...
        component_YP_projection = componentYPProjection;
    pilot3Regression.animals(animalIndex). ...
        n_valid_component_neurons = sum(validComponentNeurons);
    pilot3Regression.animals(animalIndex). ...
        reduced_residual_YP_projection = ...
        reducedResidualYPProjection;
    pilot3Regression.animals(animalIndex). ...
        reduced_beta_time = reducedBetaTime;
    pilot3Regression.animals(animalIndex). ...
        n_valid_reduced_residual_neurons = ...
        sum(validReducedResidualNeurons);
    pilot3Regression.animals(animalIndex). ...
        choice_only_residual_YP_projection = ...
        choiceOnlyResidualYPProjection;
    pilot3Regression.animals(animalIndex). ...
        choice_only_beta_time = choiceOnlyBetaTime;
    pilot3Regression.animals(animalIndex). ...
        n_valid_choice_only_residual_neurons = ...
        sum(validChoiceOnlyResidualNeurons);
    pilot3Regression.animals(animalIndex). ...
        motor_only_residual_YP_projection = ...
        motorOnlyResidualYPProjection;
    pilot3Regression.animals(animalIndex). ...
        motor_only_beta_time = motorOnlyBetaTime;
    pilot3Regression.animals(animalIndex). ...
        n_valid_motor_only_residual_neurons = ...
        sum(validMotorOnlyResidualNeurons);
    pilot3Regression.animals(animalIndex). ...
        unique_explained_ss = uniqueExplainedSS;
    pilot3Regression.animals(animalIndex). ...
        population_unique_explained_ss = populationUniqueSS;
    pilot3Regression.animals(animalIndex). ...
        relative_unique_explained_variance = ...
        relativeUniqueExplainedVariance;
    pilot3Regression.animals(animalIndex). ...
        population_full_model_R2 = populationFullModelR2;

    for windowIndex = 1:size(analysisWindows, 1)
        window = analysisWindows(windowIndex, :);
        timeMask = timeAt >= window(1) & timeAt < window(2);
        windowParameters = mean( ...
            parameterProjection(:, timeMask), 2, 'omitnan');
        pilot3Rows(end + 1, :) = { ...
            animalNames(animalIndex), window(1), window(2), ...
            windowParameters(1), windowParameters(2), ...
            windowParameters(3), windowParameters(4), ...
            sum(validNeurons)}; %#ok<SAGROW>
    end
end

pilot3WindowStats = cell2table(pilot3Rows, ...
    'VariableNames', {'Animal', 'WindowStart', 'WindowEnd', ...
    'Intercept', 'Choice', 'Release1', ...
    'ChoiceByRelease1', 'NValidNeurons'});
disp(pilot3WindowStats);

