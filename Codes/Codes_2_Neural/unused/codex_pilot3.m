%% Reproduce Figure_YP A-B after removing choice and motor main effects
yellowColor = [0.90 0.65 0.05];
purpleColor = [0.55 0.25 0.72];
figure('Color', 'w', ...
    'Name', 'Y/P after removing choice and release1 effects', ...
    'Position', [100 100 1100 470]);
tiledlayout(1, 2, 'TileSpacing', 'compact', 'Padding', 'compact');
for animalIndex = 1:numel(animalNames)
    nexttile;
    hold on;
    result = pilot3Regression.animals(animalIndex);
    timeAt = result.time_at;
    correctedProjection = result.corrected_YP_projection;
    yellowValue = reshape(correctedProjection(:, 1, :), ...
        9, numel(timeAt));
    purpleValue = reshape(correctedProjection(:, 2, :), ...
        9, numel(timeAt));

    yellowMean = mean(yellowValue, 1, 'omitnan');
    yellowSE = std(yellowValue, 0, 1, 'omitnan') / ...
        sqrt(size(yellowValue, 1));
    purpleMean = mean(purpleValue, 1, 'omitnan');
    purpleSE = std(purpleValue, 0, 1, 'omitnan') / ...
        sqrt(size(purpleValue, 1));

    fill([timeAt, fliplr(timeAt)], ...
        [yellowMean - yellowSE, ...
        fliplr(yellowMean + yellowSE)], ...
        yellowColor, 'FaceAlpha', 0.20, ...
        'EdgeColor', 'none');
    fill([timeAt, fliplr(timeAt)], ...
        [purpleMean - purpleSE, ...
        fliplr(purpleMean + purpleSE)], ...
        purpleColor, 'FaceAlpha', 0.20, ...
        'EdgeColor', 'none');
    yellowLine = plot(timeAt, yellowMean, ...
        'Color', yellowColor, 'LineWidth', 1.8);
    purpleLine = plot(timeAt, purpleMean, ...
        'Color', purpleColor, 'LineWidth', 1.8);

    pValue = nan(1, numel(timeAt));
    for timeIndex = 1:numel(timeAt)
        [~, pValue(timeIndex)] = ttest( ...
            purpleValue(:, timeIndex) - ...
            yellowValue(:, timeIndex));
    end
    significantTime = pValue < 0.05 & ...
        timeAt >= -250 & timeAt <= 500;
    upperEnvelope = max([yellowMean + yellowSE; ...
        purpleMean + purpleSE], [], 1);
    projectionRange = max(upperEnvelope) - ...
        min([yellowMean - yellowSE, purpleMean - purpleSE]);
    significanceHeight = upperEnvelope + ...
        0.04 * max(projectionRange, eps);
    plot(timeAt(significantTime), ...
        significanceHeight(significantTime), ...
        'k.', 'MarkerSize', 5);

    xline(0, '--', 'Color', [0.4 0.4 0.4]);
    yline(0, ':', 'Color', [0.65 0.65 0.65]);
    xlim([-250 500]);
    set(gca, 'XTick', -250:250:500, 'FontSize', 11);
    xlabel('Time from GO cue onset (ms)');
    ylabel('Choice/motor-corrected value-axis projection');
    title(animalNames(animalIndex));
    box off;
    if animalIndex == 2
        legend([yellowLine, purpleLine], ...
            {'Yellow', 'Purple'}, 'Location', 'best', ...
            'Box', 'off');
    end
end
sgtitle({'Yellow/Purple after removing choice and release1 main effects', ...
    'Dots: paired condition-level p < 0.05'});

%% Five-component reconstruction of Yellow/Purple trajectories
figure('Color', 'w', ...
    'Name', 'Y/P regression-component trajectories', ...
    'Position', [100 50 1200 1000]);
tiledlayout(5, 2, 'TileSpacing', 'compact', 'Padding', 'compact');
componentAxes = gobjects(5, 2);
for componentIndex = 1:numel(componentNames)
    for animalIndex = 1:numel(animalNames)
        componentAxes(componentIndex, animalIndex) = nexttile;
        hold on;
        result = pilot3Regression.animals(animalIndex);
        timeAt = result.time_at;
        componentProjection = reshape( ...
            result.component_YP_projection( ...
            componentIndex, :, :, :), ...
            9, 2, numel(timeAt));
        yellowValue = reshape(componentProjection(:, 1, :), ...
            9, numel(timeAt));
        purpleValue = reshape(componentProjection(:, 2, :), ...
            9, numel(timeAt));
        yellowMean = mean(yellowValue, 1, 'omitnan');
        purpleMean = mean(purpleValue, 1, 'omitnan');
