function [adjustedMeans, diagnostic] = adjustedColorMeans( ...
        spikes, game, nConditions, nColors)
%ADJUSTEDCOLORMEANS Estimate cell means controlling choice and release1.
    nTrials = height(game);
    colorIndex = nan(nTrials, 1);
    colorIndex(game.cue1 == "yellow") = 1;
    colorIndex(game.cue1 == "purple") = 2;
    isValid = isfinite(game.condition) & ...
        isfinite(game.choice) & ...
        isfinite(game.release1) & ...
        isfinite(colorIndex) & ...
        all(isfinite(spikes), 2);
    assert(any(isValid), ...
        'No valid trials remain for adjusted Yellow/Purple means.');

    condition = game.condition(isValid);
    color = colorIndex(isValid);
    choice = double(game.choice(isValid));
    release = double(game.release1(isValid));
    cellIndex = (condition - 1)*nColors + color;
    nCells = nConditions*nColors;
    cellDesign = full(sparse( ...
        (1:sum(isValid))', cellIndex, 1, sum(isValid), nCells));
    assert(all(sum(cellDesign, 1) > 0), ...
        'Every condition/color cell must contain valid trials.');

    choice = choice - mean(choice);
    release = release - mean(release);
    design = [cellDesign, choice, release];
    designRank = rank(design);
    assert(designRank == size(design, 2), ...
        ['The additive color/choice/release1 model is rank deficient. ' ...
        'The adjusted color effect is not identifiable.']);

    coefficients = design \ spikes(isValid, :);
    adjustedMeans = reshape(coefficients(1:nCells, :), ...
        nColors, nConditions, []);
    adjustedMeans = permute(adjustedMeans, [2 1 3]);
    diagnostic = struct( ...
        'n_trials', sum(isValid), ...
        'n_predictors', size(design, 2), ...
        'design_rank', designRank, ...
        'condition_number', cond(design));
end